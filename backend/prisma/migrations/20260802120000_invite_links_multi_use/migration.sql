-- Приглашение стало ссылкой, а не кодом под диктовку: перешёл — и уже внутри.
--
-- Раз ссылку кидают в чат команде, одноразовость мешает: по ней должен зайти
-- каждый, кому её переслали, пока не истёк срок. Одноразовость держалась на
-- usedById, и теперь это поле значит «первый перешедший», а счёт ведёт
-- отдельная колонка.
--
-- Уже использованным кодам ставим единицу: по ним ровно один человек и зашёл.

ALTER TABLE "InviteCode" ADD COLUMN "usedCount" INTEGER NOT NULL DEFAULT 0;

UPDATE "InviteCode" SET "usedCount" = 1 WHERE "usedById" IS NOT NULL;
